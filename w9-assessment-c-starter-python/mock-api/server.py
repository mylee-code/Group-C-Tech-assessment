_lock = threading.Lock()
_request_count = 0
_hits = {}  # client address -> recent request times


def log(level, message):
    stamp = datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")
    print(f"{stamp} | {level} | {message}", flush=True)


def error_body(status, message):
    return {"error": {"status": status, "message": message}}


def meta(**extra):
    global _request_count
    with _lock:
        _request_count += 1
        n = _request_count
    stamp = datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")
    return {"request_id": f"req_{n:05d}", "served_at": stamp,
            "source": "Neighborhood Tech Hub mock API (synthetic data for i.c.stars Assessment C)", **extra}


def is_rate_limited(client):
    now = time.monotonic()
    with _lock:
        recent = [t for t in _hits.get(client, []) if now - t < RATE_LIMIT_WINDOW_S]
        recent.append(now)
        _hits[client] = recent
        return len(recent) > RATE_LIMIT_MAX


class Handler(BaseHTTPRequestHandler):
    server_version = "MockWorkshopsAPI/1.0"

    def log_message(self, fmt, *args):  # silence default logging; we log our own way
        pass

    def finish_with(self, status, body, headers=None):
        text = body if isinstance(body, str) else json.dumps(body, indent=2)
        data = text.encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        for key, value in (headers or {}).items():
            self.send_header(key, value)
        self.end_headers()
        self.wfile.write(data)
        log("WARN" if status >= 400 else "INFO", f"{self.command} {self.path} -> {status}")

    def do_POST(self):
        self.finish_with(405, error_body(405, "Only GET requests are supported by this mock API."))

    do_PUT = do_PATCH = do_DELETE = do_POST

    def do_GET(self):
        parts = urlsplit(self.path)
        path = parts.path.rstrip("/") or "/"
        simulate = (parse_qs(parts.query).get("simulate", [""])[0]).lower()

        if path in ("/", "/health"):
            return self.finish_with(200, {"status": "ok", "endpoints": ["/health", "/api/v1/workshops", "/api/v1/workshops/<id>"]})
        if not path.startswith("/api/v1/workshops"):
            return self.finish_with(404, error_body(404, f"No endpoint at {parts.path}. Try /api/v1/workshops/<id>."))
        if is_rate_limited(self.client_address[0]):
            return self.finish_with(429, error_body(429, "Too many requests. Wait 2 seconds, then try again."), {"Retry-After": "2"})
        if self.headers.get("x-api-key") != API_KEY:
            return self.finish_with(401, error_body(401, "Missing or invalid API key. Send it in the x-api-key header."))

        # Simulated failures for error-handling practice
        if simulate == "500":
            return self.finish_with(500, error_body(500, "Simulated server failure."))
        if simulate == "503":
            return self.finish_with(503, error_body(503, "Simulated outage. Try again later."), {"Retry-After": "2"})
        if simulate == "429":
            return self.finish_with(429, error_body(429, "Simulated rate limit. Wait 2 seconds."), {"Retry-After": "2"})
        if simulate == "badjson":
            return self.finish_with(200, '{"data": {"id": 1, "title": "Broken resp')
        if simulate == "slow":
            time.sleep(SLOW_S)

        if path == "/api/v1/workshops":
            return self.finish_with(200, {"data": WORKSHOPS, "meta": meta(count=len(WORKSHOPS))})
        match = re.fullmatch(r"/api/v1/workshops/(\d+)", path)
        if not match:
            return self.finish_with(400, error_body(400, "Workshop id must be a whole number, e.g. /api/v1/workshops/7."))
        workshop = next((w for w in WORKSHOPS if w["id"] == int(match.group(1))), None)
        if workshop is None:
            return self.finish_with(404, error_body(404, f"No workshop with id {match.group(1)}. Valid ids are 1-{len(WORKSHOPS)}."))
        return self.finish_with(200, {"data": workshop, "meta": meta()})


